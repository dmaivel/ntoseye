pub fn ntstatus_name(code: u32) -> Option<&'static str> {
    NTSTATUS_NAMES
        .iter()
        .find(|(value, _)| *value == code)
        .map(|(_, name)| *name)
}

pub fn win32_error_name(code: u32) -> Option<&'static str> {
    WIN32_NAMES
        .iter()
        .find(|(value, _)| *value == code)
        .map(|(_, name)| *name)
}
